"""Analysis for the conference paper.

Works on the raw per-repetition CSVs (one row per repetition), so the noise of
every platform is measured instead of assumed. Every number that goes into the
paper is written to figures/paper/paper_numbers.{txt,tex} under a fixed key, so
the text can quote the run that produced it (\\pn{key} in LaTeX).

Definitions (all per matrix, at a fixed thread count):
  t(m)            median kernel time over repetitions for candidate m
  candidates      none, rcm, amd, nd, gp   ("none" = keep the original order)
  speedup(m)      t(none) / t(m)
  pre(m)          permutation compute time + apply time (s); pre(none) = 0
  cost_K(m)       pre(m) + K * t(m)        (K = number of SpMV calls)
  best            argmin t(m)  (kernel-only)  or  argmin cost_K(m)  (cost-aware)
  co-best set     {m : t(m) <= (1 + tie) * t(best)}
  portability     fraction of the target platform's best performance obtained
                  with the source platform's choice: t_T(best_T) / t_T(best_S)
                  (or the same ratio of cost_K); 1.0 = no loss
  break-even      pre(m) / (t(none) - t(m)) iterations; infinite if no gain
"""

import logging
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

from utils.data.io import normalize_reorder_times, read_csv

CANDIDATES = ["none", "rcm", "amd", "nd", "gp"]
METHODS = ["rcm", "amd", "nd", "gp"]
LABELS = {"none": "None", "rcm": "RCM", "amd": "AMD", "nd": "ND", "gp": "GP"}
COLORS = {"none": "#777777", "rcm": "#3B6EA8", "amd": "#B45F2A", "nd": "#3D8B62", "gp": "#7A4E9C"}
PLATFORMS = {"x86": "x86_results", "arm": "arm_results"}
# Structurally identical pairs (same pattern, different values): a built-in
# consistency check, and a source of double counting in the statistics.
TWINS = [("venkat01", "venkat25"), ("thermomech_TC", "thermomech_TK")]
THREAD_WORDS = {1: "one", 2: "two", 4: "four"}


@dataclass
class Numbers:
    """Collects every reported value under a stable key."""
    values: dict = field(default_factory=dict)
    notes: dict = field(default_factory=dict)

    def put(self, key, value, kind="frac", note=""):
        if not key.replace(".", "").isalnum():
            raise ValueError(f"bad key {key!r}: use letters, digits and dots only")
        self.values[key] = (value, kind)
        if note:
            self.notes[key] = note

    @staticmethod
    def fmt(value, kind):
        if value is None or (isinstance(value, float) and not np.isfinite(value)):
            return "inf" if value == np.inf else "n/a"
        if kind == "frac":
            return f"{100 * value:.1f}"        # percent, rounded to 0.1
        if kind == "ratio":
            return f"{value:.3f}"
        if kind == "count":
            return f"{int(value)}"
        if kind == "iters":
            return f"{value:.0f}"
        return str(value)

    def write(self, out_dir: Path):
        out_dir.mkdir(parents=True, exist_ok=True)
        with open(out_dir / "paper_numbers.txt", "w") as f:
            f.write("# key = formatted (raw). frac -> percent rounded to 0.1; ratio -> 3 decimals\n")
            for k, (v, kind) in sorted(self.values.items()):
                note = f"   # {self.notes[k]}" if k in self.notes else ""
                f.write(f"{k} = {self.fmt(v, kind)} ({v!r}){note}\n")
        with open(out_dir / "paper_numbers.tex", "w") as f:
            f.write("% Generated by scripts/paper_analysis.py. Use \\pn{key}; unknown keys print ??key.\n")
            f.write("\\makeatletter\n")
            for k, (v, kind) in sorted(self.values.items()):
                f.write(f"\\expandafter\\def\\csname pn@{k}\\endcsname{{{self.fmt(v, kind)}}}\n")
            f.write("\\newcommand{\\pn}[1]{\\ifcsname pn@#1\\endcsname\\csname pn@#1\\endcsname"
                    "\\else\\textbf{??#1}\\fi}\n\\makeatother\n")


# ---------------------------------------------------------------- loading

def load(results_dir: Path, methodology: str = "ios"):
    """Return {platform: (raw_df, reorder_df)} for the platforms that have data."""
    data = {}
    for plat, sub in PLATFORMS.items():
        raw = read_csv(results_dir / sub / f"{methodology}.csv", f"{plat} {methodology}")
        reo = normalize_reorder_times(read_csv(results_dir / sub / "reorder_times.csv", f"{plat} reorder"))
        if raw is None:
            continue
        if "rep" not in raw.columns:
            logging.warning("%s: legacy CSV without repetitions; noise cannot be measured", plat)
            raw = raw.assign(rep=0)
        data[plat] = (raw, reo)
    return data


def medians(raw: pd.DataFrame) -> pd.DataFrame:
    keys = ["matrix", "category", "reordering", "threads"]
    g = raw.groupby(keys)["time_ms"]
    out = g.median().rename("time_ms").to_frame()
    out["n_reps"] = g.size()
    out["spread"] = (g.max() - g.min()) / out["time_ms"]           # (max-min)/median
    return out.reset_index()


def wide(med: pd.DataFrame, threads: int, dedupe=False) -> pd.DataFrame:
    """Matrix x candidate table of median times (ms) at one thread count."""
    w = med[med.threads == threads].pivot_table(index="matrix", columns="reordering", values="time_ms")
    w = w.reindex(columns=CANDIDATES).dropna()
    if dedupe:
        w = w.drop(index=[b for _, b in TWINS if b in w.index])
    return w


def preprocessing(reo: pd.DataFrame, index) -> pd.DataFrame:
    p = reo.pivot_table(index="matrix", columns="reordering", values="time_s").reindex(index)
    p["none"] = 0.0
    return p.reindex(columns=CANDIDATES)


# ---------------------------------------------------------------- noise

def noise_report(plat, raw, med, nums: Numbers):
    reps = int(med["n_reps"].min())
    nums.put(f"{plat}.reps", reps, "count")
    if reps > 1:
        nums.put(f"{plat}.spread.median", float(med["spread"].median()), "frac",
                 "(max-min)/median over repetitions, median over all matrix/method/thread cells")
        nums.put(f"{plat}.spread.ninetyfive", float(med["spread"].quantile(0.95)), "frac")
        if "pos" in raw.columns:
            # order effect: time relative to the cell median, by position in the shuffled order
            keys = ["matrix", "reordering", "threads"]
            rel = raw["time_ms"] / raw.groupby(keys)["time_ms"].transform("median")
            by_pos = rel.groupby(raw["pos"]).median()
            for pos, v in by_pos.items():
                nums.put(f"{plat}.orderpos{int(pos)}", float(v), "ratio",
                         "median time / cell median at this position of the shuffled order")
    for t in sorted(med.threads.unique()):
        w = wide(med, t)
        diffs = []
        for a, b in TWINS:
            if a in w.index and b in w.index:
                diffs.extend((abs(w.loc[a] - w.loc[b]) / ((w.loc[a] + w.loc[b]) / 2)).tolist())
        if diffs:
            nums.put(f"{plat}.t{t}.twins.maxdiff", float(np.max(diffs)), "frac",
                     "max relative time difference between structurally identical matrices")


# ---------------------------------------------------------------- outcomes

def outcomes(plat, med, threads, thr, nums: Numbers, dedupe):
    w = wide(med, threads, dedupe)
    nums.put(f"{plat}.t{threads}.matrices", len(w), "count")
    rows = []
    for m in METHODS:
        s = w["none"] / w[m]
        win, loss = float((s > 1 + thr).mean()), float((s < 1 - thr).mean())
        geo = float(np.exp(np.log(s).mean()))
        nums.put(f"{plat}.t{threads}.{m}.win", win)
        nums.put(f"{plat}.t{threads}.{m}.loss", loss)
        nums.put(f"{plat}.t{threads}.{m}.median", float(s.median()), "ratio")
        nums.put(f"{plat}.t{threads}.{m}.geomean", geo, "ratio")
        rows.append({"platform": plat, "threads": threads, "method": m, "win": win, "loss": loss,
                     "neutral": 1 - win - loss, "median_speedup": s.median(), "geomean_speedup": geo})
    return rows


# ---------------------------------------------------------------- selection

def choice_costs(w: pd.DataFrame, pre: pd.DataFrame, horizon):
    """Cost of each candidate per matrix: kernel time (horizon None) or cost_K in seconds."""
    if horizon is None:
        return w.copy()
    return pre.reindex(w.index) + horizon * w / 1000.0


def selection(med_s, med_t, reo_s, reo_t, threads, horizon, tie, dedupe):
    """Per-matrix choice on the source platform s and its value on the target t."""
    ws, wt = wide(med_s, threads, dedupe), wide(med_t, threads, dedupe)
    idx = ws.index.intersection(wt.index)
    cs = choice_costs(ws.loc[idx], preprocessing(reo_s, idx), horizon)
    ct = choice_costs(wt.loc[idx], preprocessing(reo_t, idx), horizon)
    best_s, best_t = cs.idxmin(axis=1), ct.idxmin(axis=1)
    got = np.array([ct.loc[i, best_s[i]] for i in idx])
    frac = ct.min(axis=1).to_numpy() / got
    cobest_s = cs.le((1 + tie) * cs.min(axis=1), axis=0)
    cobest_t = ct.le((1 + tie) * ct.min(axis=1), axis=0)
    overlap = (cobest_s & cobest_t).any(axis=1)
    return pd.DataFrame({"best_src": best_s, "best_tgt": best_t, "portability": frac,
                         "tie_agree": overlap, "ambiguous_src": cobest_s.sum(axis=1) > 1,
                         "ambiguous_tgt": cobest_t.sum(axis=1) > 1}, index=idx)


def heuristic(med, reo, threads, horizon, rule, dedupe):
    """Fraction of the platform's own best obtained by a fixed rule (always m)."""
    w = wide(med, threads, dedupe)
    c = choice_costs(w, preprocessing(reo, w.index), horizon)
    return c.min(axis=1) / c[rule]


def breakeven(med, reo, threads, dedupe):
    w = wide(med, threads, dedupe)
    pre = preprocessing(reo, w.index)
    out = {}
    for m in METHODS:
        gain_s = (w["none"] - w[m]) / 1000.0
        out[m] = np.where(gain_s > 0, pre[m] / gain_s.where(gain_s > 0), np.inf)
    return pd.DataFrame(out, index=w.index)


# ---------------------------------------------------------------- plots

def plot_portability(sel_by_dir, threads, out_dir):
    import matplotlib.pyplot as plt
    from utils.plotting.common import SINGLE_COLUMN_WIDTH, paper_axes, save_figure
    fig, ax = plt.subplots(figsize=(SINGLE_COLUMN_WIDTH, 2.2))
    styles = {("x86", "arm"): ("-", "x86 choice run on ARM"), ("arm", "x86"): ("--", "ARM choice run on x86")}
    for key, sel in sel_by_dir.items():
        v = np.sort(sel["portability"].to_numpy())
        ax.step(v, np.arange(1, len(v) + 1) / len(v), where="post",
                linestyle=styles[key][0], color="#222222", label=styles[key][1])
    ax.axvline(0.95, color="#999999", linestyle=":", linewidth=0.8)
    ax.set_xlabel("Share of the target's best performance")
    ax.set_ylabel("Fraction of matrices")
    ax.set_xlim(left=max(0.0, min(s["portability"].min() for s in sel_by_dir.values()) - 0.02), right=1.005)
    ax.legend(loc="upper left")
    paper_axes(ax, grid_axis="both")
    fig.tight_layout()
    for ext in ("pdf", "png"):
        save_figure(out_dir, f"portability_cdf_t{threads}.{ext}")
    plt.close(fig)


def plot_breakeven(be_by_plat, threads, out_dir):
    import matplotlib.pyplot as plt
    from utils.plotting.common import DOUBLE_COLUMN_WIDTH, paper_axes, save_figure
    fig, axes = plt.subplots(1, len(be_by_plat), figsize=(DOUBLE_COLUMN_WIDTH, 2.1), sharey=True, squeeze=False)
    ks = np.logspace(1, 6, 201)
    for ax, (plat, be) in zip(axes[0], be_by_plat.items()):
        for m in METHODS:
            ax.plot(ks, [(be[m] <= k).mean() for k in ks], color=COLORS[m], label=LABELS[m])
        ax.set_xscale("log")
        ax.set_ylim(0, 1)
        ax.set_title(plat.upper() if plat == "arm" else plat)
        ax.set_xlabel("SpMV calls $K$")
        paper_axes(ax, grid_axis="both")
    axes[0][0].set_ylabel("Matrices amortized within $K$")
    axes[0][-1].legend(loc="upper left")
    fig.tight_layout()
    for ext in ("pdf", "png"):
        save_figure(out_dir, f"breakeven_cdf_t{threads}.{ext}")
    plt.close(fig)


# ---------------------------------------------------------------- driver

def run(results_dir=Path("results"), out_dir="paper", methodology="ios", threads_list=(1, 2, 4),
        fig_threads=4, thr=0.05, tie=0.02, horizons=(100, 1000, 10000, 100000), dedupe=False,
        make_plots=True):
    nums = Numbers()
    data = load(Path(results_dir), methodology)
    if not data:
        raise SystemExit(f"no {methodology}.csv found under {results_dir}")
    med = {p: medians(raw) for p, (raw, _) in data.items()}
    reo = {p: r for p, (_, r) in data.items()}
    nums.put("threshold", thr, "frac", "win/loss threshold")
    nums.put("tie", tie, "frac", "co-best tolerance")

    for p, (raw, _) in data.items():
        noise_report(p, raw, med[p], nums)

    rows = []
    for p in data:
        for t in threads_list:
            rows += outcomes(p, med[p], t, thr, nums, dedupe)
    tables = {"outcomes": pd.DataFrame(rows)}

    be_by_plat = {}
    for p in data:
        if reo[p] is None:
            continue
        for t in threads_list:
            be = breakeven(med[p], reo[p], t, dedupe)
            for m in METHODS:
                nums.put(f"{p}.t{t}.{m}.never", float(np.isinf(be[m]).mean()), "frac",
                         "share of matrices with no kernel gain (never amortized)")
                for k in horizons:
                    nums.put(f"{p}.t{t}.{m}.within{k}", float((be[m] <= k).mean()), "frac",
                             f"share of all matrices amortized within {k} SpMV calls")
            if t == fig_threads:
                be_by_plat[p] = be
                tables[f"breakeven_{p}_t{t}"] = be

    if {"x86", "arm"} <= set(data) and reo["x86"] is not None and reo["arm"] is not None:
        sel_fig = {}
        for t in threads_list:
            for hz in [None, *horizons]:
                hk = "kernel" if hz is None else f"cost{hz}"
                for s, g in (("x86", "arm"), ("arm", "x86")):
                    sel = selection(med[s], med[g], reo[s], reo[g], t, hz, tie, dedupe)
                    pre = f"{s}to{g}.t{t}.{hk}"
                    nums.put(f"{pre}.exact", float((sel.best_src == sel.best_tgt).mean()))
                    nums.put(f"{pre}.tieagree", float(sel.tie_agree.mean()))
                    nums.put(f"{pre}.within5", float((sel.portability >= 0.95).mean()))
                    nums.put(f"{pre}.worst", float(sel.portability.min()), "ratio")
                    nums.put(f"{pre}.ambiguous", float(sel.ambiguous_src.mean()), "frac",
                             "matrices whose best on the source is within the tie tolerance of another")
                    if hz is None and s == "x86":
                        nums.put(f"{pre}.srcnone.count", int((sel.best_src == "none").sum()), "count")
                        nums.put(f"{pre}.srcnone.tgtnone.count",
                                 int(((sel.best_src == "none") & (sel.best_tgt == "none")).sum()), "count")
                    if t == fig_threads and hz is None:
                        sel_fig[(s, g)] = sel
                        tables[f"selection_{s}to{g}_t{t}"] = sel
            for p in ("x86", "arm"):
                for rule in ("none", "rcm"):
                    h = heuristic(med[p], reo[p], t, None, rule, dedupe)
                    nums.put(f"{p}.t{t}.always{rule}.within5", float((h >= 0.95).mean()), "frac",
                             f"matrices where always choosing {rule} is within 5% of the best")
        if make_plots:
            plot_portability(sel_fig, fig_threads, out_dir)
    if make_plots and be_by_plat:
        plot_breakeven(be_by_plat, fig_threads, out_dir)

    out = Path("figures") / out_dir
    nums.write(out)
    for name, df in tables.items():
        df.to_csv(out / f"{name}.csv")
    return nums, tables
